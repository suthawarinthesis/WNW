create policy "public read academic files" on public.academic_files
for select to anon, authenticated using (published = true or public.is_site_admin());
drop policy if exists "admin insert academic files" on public.academic_files;
create policy "admin insert academic files" on public.academic_files
for insert to authenticated with check (public.is_site_admin());
drop policy if exists "admin update academic files" on public.academic_files;
create policy "admin update academic files" on public.academic_files
for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
drop policy if exists "admin delete academic files" on public.academic_files;
