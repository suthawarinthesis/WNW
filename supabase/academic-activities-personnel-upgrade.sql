-- ---------- Academic announcements ----------
create table if not exists public.academic_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text default '',
  body text default '',
  publish_date date default current_date,
  pinned boolean not null default false,
  published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

alter table public.academic_posts enable row level security;
drop policy if exists "public read academic posts" on public.academic_posts;
create policy "public read academic posts" on public.academic_posts
for select to anon, authenticated using (published = true or public.is_site_admin());
drop policy if exists "admin insert academic posts" on public.academic_posts;
create policy "admin insert academic posts" on public.academic_posts
for insert to authenticated with check (public.is_site_admin());
drop policy if exists "admin update academic posts" on public.academic_posts;
create policy "admin update academic posts" on public.academic_posts
for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
drop policy if exists "admin delete academic posts" on public.academic_posts;
create policy "admin delete academic posts" on public.academic_posts
for delete to authenticated using (public.is_site_admin());

create index if not exists academic_posts_public_idx
on public.academic_posts (published, pinned desc, publish_date desc, sort_order asc);

-- ---------- Academic files ----------
create table if not exists public.academic_files (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'academic' check (category in ('academic','finance','quality','other')),
  description text default '',
  file_url text not null,
  file_name text default '',
  file_type text default '',
  file_size text default '',
  publish_date date default current_date,
  published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

alter table public.academic_files enable row level security;
